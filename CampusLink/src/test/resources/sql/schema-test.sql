-- estrutura local usada pelos testes de integracao e pelos testes que ja existem
CREATE TABLE public."USUARIOS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    telefone TEXT,
    datanasc DATE,
    senha TEXT NOT NULL,
    perfil TEXT NOT NULL,
    status BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public."ADMINISTRADOR" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL UNIQUE REFERENCES public."USUARIOS"(id),
    matricula TEXT UNIQUE,
    master BOOLEAN DEFAULT FALSE
);

CREATE TABLE public."ALUNOS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    rgm TEXT UNIQUE,
    id_usuario BIGINT NOT NULL UNIQUE REFERENCES public."USUARIOS"(id)
);

CREATE TABLE public."PROFESSORES" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula TEXT UNIQUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    id_usuario BIGINT NOT NULL UNIQUE REFERENCES public."USUARIOS"(id)
);

CREATE TABLE public."TURMAS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_turma TEXT NOT NULL,
    descricao TEXT,
    id_professores BIGINT[] DEFAULT ARRAY[]::BIGINT[],
    id_alunos BIGINT[] DEFAULT ARRAY[]::BIGINT[],
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    id_proprietario BIGINT REFERENCES public."PROFESSORES"(id)
);

CREATE TABLE public."CONTEUDOS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turma BIGINT[] NOT NULL,
    id_professor BIGINT NOT NULL REFERENCES public."PROFESSORES"(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    titulo TEXT NOT NULL,
    descricao TEXT,
    tipo TEXT,
    url TEXT,
    duracao_estimada TEXT,
    prioridade TEXT,
    status TEXT NOT NULL DEFAULT 'ativo',
    comentario_admin TEXT,
    revisao_solicitada BOOLEAN DEFAULT FALSE,
    revisao_solicitada_em TIMESTAMPTZ
);

CREATE TABLE public."LOGS_SESSOES" (
    sessao_log_id UUID PRIMARY KEY,
    usuario_id BIGINT REFERENCES public."USUARIOS"(id),
    inicio TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    fim TIMESTAMPTZ,
    status TEXT DEFAULT 'ATIVA',
    log_completo TEXT,
    historico_gerado_em TIMESTAMPTZ
);

CREATE TABLE public."LOGS_EVENTOS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_log_id UUID REFERENCES public."LOGS_SESSOES"(sessao_log_id),
    data_hora TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    nivel TEXT,
    classe TEXT,
    operacao TEXT,
    operacao_id UUID,
    mensagem TEXT,
    detalhes JSONB,
    excecao TEXT
);

-- estas tabelas permitem executar os testes antigos sem consultar o banco de desenvolvimento
CREATE TABLE public."ALUNO_TURMA" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno BIGINT REFERENCES public."ALUNOS"(id),
    id_turma BIGINT REFERENCES public."TURMAS"(id),
    status TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public."PROFESSOR_TURMA" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_professor BIGINT REFERENCES public."PROFESSORES"(id),
    id_turma BIGINT REFERENCES public."TURMAS"(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public."DISPONIBILIDADES" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno BIGINT REFERENCES public."ALUNOS"(id),
    data DATE,
    horas_disponiveis INTEGER,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public."DENUNCIAS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conteudo BIGINT REFERENCES public."CONTEUDOS"(id),
    id_aluno BIGINT REFERENCES public."ALUNOS"(id),
    id_professor BIGINT REFERENCES public."PROFESSORES"(id),
    motivo TEXT,
    status TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public."EVENTOS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turma BIGINT REFERENCES public."TURMAS"(id),
    id_professor BIGINT REFERENCES public."PROFESSORES"(id),
    titulo TEXT,
    tipo TEXT,
    descricao TEXT,
    data_hora TIMESTAMP,
    data_fim TIMESTAMP,
    status TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    prioridade TEXT
);

CREATE TABLE public."EVENTO_CONTEUDO" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evento BIGINT REFERENCES public."EVENTOS"(id),
    id_conteudo BIGINT REFERENCES public."CONTEUDOS"(id)
);

CREATE TABLE public."ARQUIVOS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conteudo BIGINT REFERENCES public."CONTEUDOS"(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    bucket_id TEXT,
    storage_path TEXT
);

CREATE TABLE public."CHAMADOS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES public."USUARIOS"(id),
    assunto VARCHAR(150) NOT NULL,
    descricao TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'aberto',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    concluido_em TIMESTAMPTZ,
    id_admin_conclusao BIGINT REFERENCES public."USUARIOS"(id)
);

CREATE TABLE public."CHAMADO_RESPOSTAS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chamado BIGINT NOT NULL REFERENCES public."CHAMADOS"(id),
    id_admin_usuario BIGINT REFERENCES public."USUARIOS"(id),
    id_usuario BIGINT REFERENCES public."USUARIOS"(id),
    tipo_autor TEXT NOT NULL,
    resposta TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Estrutura usada pelos testes existentes em um PostgreSQL exclusivo para testes.
CREATE TABLE IF NOT EXISTS public."USUARIOS" (
    id bigint PRIMARY KEY, nome text, email text, telefone text, datanasc date,
    senha text, perfil text, status boolean, created_at timestamptz, anonimizado_em timestamptz
);
CREATE TABLE IF NOT EXISTS public."ALUNOS" (
    id bigint PRIMARY KEY, created_at timestamptz, rgm text, id_usuario bigint
);
CREATE TABLE IF NOT EXISTS public."PROFESSORES" (
    id bigint PRIMARY KEY, matricula text, created_at timestamptz, id_usuario bigint
);
CREATE TABLE IF NOT EXISTS public."ADMINISTRADOR" (
    id bigint PRIMARY KEY, id_usuario bigint, matricula text, master boolean
);
CREATE TABLE IF NOT EXISTS public."TURMAS" (
    id bigint PRIMARY KEY, nome_turma text, id_professores bigint[], id_alunos bigint[],
    created_at timestamptz, id_proprietario bigint
);
CREATE TABLE IF NOT EXISTS public."ALUNO_TURMA" (
    id bigint PRIMARY KEY, id_aluno bigint, id_turma bigint, status text, created_at timestamptz
);
CREATE TABLE IF NOT EXISTS public."PROFESSOR_TURMA" (
    id bigint PRIMARY KEY, id_professor bigint, id_turma bigint, created_at timestamptz
);
CREATE TABLE IF NOT EXISTS public."DISPONIBILIDADES" (
    id bigint PRIMARY KEY, id_aluno bigint, data date, horas_disponiveis integer, created_at timestamptz
);
CREATE TABLE IF NOT EXISTS public."DENUNCIAS" (
    id bigint PRIMARY KEY, id_conteudo bigint, id_aluno bigint, id_professor bigint,
    motivo text, status text, created_at timestamptz
);
CREATE TABLE IF NOT EXISTS public."CONTEUDOS" (
    id bigint PRIMARY KEY, id_turma bigint[], id_professor bigint, created_at timestamptz,
    titulo text, descricao text, tipo text, duracao_estimada text, prioridade text,
    status text, revisao_solicitada boolean
);
CREATE TABLE IF NOT EXISTS public."EVENTOS" (
    id bigint PRIMARY KEY, id_turma bigint, id_professor bigint, titulo text, tipo text,
    descricao text, data_hora timestamp, status text, created_at timestamptz
);
CREATE TABLE IF NOT EXISTS public."EVENTO_CONTEUDO" (
    id bigint PRIMARY KEY, id_evento bigint, id_conteudo bigint
);
CREATE TABLE IF NOT EXISTS public."ARQUIVOS" (
    id bigint PRIMARY KEY, id_conteudo bigint, created_at timestamptz, bucket_id text, storage_path text
);
CREATE TABLE IF NOT EXISTS public."PROGRESSO_CONTEUDO" (
    id bigint PRIMARY KEY, id_aluno bigint, id_conteudo bigint
);
CREATE TABLE IF NOT EXISTS public."TURMA_ATIVIDADE" (
    id bigint PRIMARY KEY, id_usuario bigint, id_turma bigint, alterado_em timestamptz
);
CREATE TABLE IF NOT EXISTS public."CONSENTIMENTOS" (
    id bigint PRIMARY KEY, id_usuario bigint, tipo text, id_termo bigint,
    hash_sha256 text, aceito_em timestamptz, revogado_em timestamptz
);
CREATE TABLE IF NOT EXISTS public."LOGS_EVENTOS" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, data_hora timestamptz DEFAULT clock_timestamp(),
    nivel text, classe text, mensagem text, detalhes jsonb, excecao text,
    sessao_log_id uuid, operacao text, operacao_id uuid
);
CREATE TABLE IF NOT EXISTS public."LOGS_SESSOES" (
    sessao_log_id uuid PRIMARY KEY, usuario_id bigint, inicio timestamptz,
    status text, log_completo text, fim timestamptz, historico_gerado_em timestamptz
);

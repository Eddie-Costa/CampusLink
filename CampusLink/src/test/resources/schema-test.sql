CREATE TABLE "USUARIOS" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome text, email text UNIQUE NOT NULL, telefone text, datanasc date,
    senha text, perfil text, status boolean DEFAULT true, created_at timestamptz DEFAULT now()
);
CREATE TABLE "ALUNOS" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at timestamptz DEFAULT now(),
    rgm text UNIQUE, id_usuario bigint REFERENCES "USUARIOS"(id)
);
CREATE TABLE "PROFESSORES" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, matricula text UNIQUE,
    created_at timestamptz DEFAULT now(), id_usuario bigint REFERENCES "USUARIOS"(id)
);
CREATE TABLE "ADMINISTRADOR" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, matricula text UNIQUE,
    created_at timestamptz DEFAULT now(), id_usuario bigint REFERENCES "USUARIOS"(id)
);
CREATE TABLE "TURMAS" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome_turma text,
    id_professores bigint[], id_alunos bigint[], created_at timestamptz DEFAULT now(),
    id_proprietario bigint REFERENCES "PROFESSORES"(id), descricao text
);
CREATE TABLE "ALUNO_TURMA" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno bigint REFERENCES "ALUNOS"(id), id_turma bigint REFERENCES "TURMAS"(id),
    status text DEFAULT 'ativo', created_at timestamptz DEFAULT now()
);
CREATE TABLE "PROFESSOR_TURMA" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_professor bigint REFERENCES "PROFESSORES"(id), id_turma bigint REFERENCES "TURMAS"(id),
    created_at timestamptz DEFAULT now()
);
CREATE TABLE "CONTEUDOS" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_turma bigint[],
    id_professor bigint REFERENCES "PROFESSORES"(id), created_at timestamptz DEFAULT now(),
    titulo text, descricao text, tipo text, url text, duracao_estimada text, prioridade text,
    status text DEFAULT 'ativo', revisao_solicitada boolean DEFAULT false, revisao_solicitada_em timestamptz,
    comentario_admin text
);
CREATE TABLE "ARQUIVOS" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_conteudo bigint REFERENCES "CONTEUDOS"(id),
    created_at timestamptz DEFAULT now(), bucket_id text, storage_path text,
    nome_original text, mime_type text, tamanho_bytes bigint, uploaded_by uuid
);
CREATE TABLE "DENUNCIAS" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conteudo bigint REFERENCES "CONTEUDOS"(id), id_aluno bigint REFERENCES "ALUNOS"(id),
    id_professor bigint REFERENCES "PROFESSORES"(id), motivo text,
    status text DEFAULT 'pendente', created_at timestamptz DEFAULT now()
);
CREATE TABLE "EVENTOS" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_turma bigint, id_professor bigint,
    titulo text, tipo text, descricao text, data_hora timestamp, data_fim timestamp,
    status text, created_at timestamptz DEFAULT now(), prioridade text
);
CREATE TABLE "EVENTO_CONTEUDO" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_evento bigint, id_conteudo bigint
);
CREATE TABLE "DISPONIBILIDADES" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_aluno bigint,
    data date, horas_disponiveis integer, created_at timestamptz DEFAULT now()
);
CREATE TABLE "LOGS_SESSOES" (
    sessao_log_id uuid PRIMARY KEY, usuario_id bigint, inicio timestamptz DEFAULT now(), fim timestamptz,
    status text DEFAULT 'ATIVA', log_completo text, historico_gerado_em timestamptz
);
CREATE TABLE "LOGS_EVENTOS" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sessao_log_id uuid REFERENCES "LOGS_SESSOES"(sessao_log_id),
    data_hora timestamptz DEFAULT clock_timestamp(), nivel text, classe text, operacao text,
    operacao_id text, mensagem text, detalhes jsonb, excecao text
);

CREATE SEQUENCE usuario_id_seq;

CREATE TABLE "USUARIOS" (
  id integer DEFAULT nextval('usuario_id_seq') NOT NULL PRIMARY KEY,
  nome text NOT NULL,
  email text UNIQUE,
  telefone text UNIQUE,
  datanasc date NOT NULL,
  senha text NOT NULL,
  perfil text NOT NULL,
  status boolean NOT NULL,
  created_at date DEFAULT CURRENT_DATE NOT NULL
);

CREATE TABLE "ADMINISTRADOR" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matricula text NOT NULL UNIQUE,
  id_usuario bigint NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  master boolean DEFAULT false NOT NULL
);

CREATE TABLE "ALUNOS" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  rgm text NOT NULL UNIQUE,
  id_usuario bigint NOT NULL
);

CREATE TABLE "PROFESSORES" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matricula text NOT NULL UNIQUE,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  id_usuario bigint NOT NULL
);

CREATE TABLE "TURMAS" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_turma text NOT NULL,
  id_professores bigint[],
  id_alunos bigint[],
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  descricao text,
  id_proprietario bigint NOT NULL
);

CREATE TABLE "ALUNO_TURMA" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aluno bigint NOT NULL,
  id_turma bigint NOT NULL,
  situacao_aluno text NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL
);

CREATE TABLE "PROFESSOR_TURMA" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_professor bigint NOT NULL,
  id_turma bigint NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL
);

CREATE TABLE "CONTEUDOS" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_turma bigint[] NOT NULL,
  id_professor bigint NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  titulo text NOT NULL,
  descricao text NOT NULL,
  tipo text NOT NULL,
  url text,
  duracao_estimada text NOT NULL,
  prioridade text NOT NULL,
  status text DEFAULT 'ativo' NOT NULL CHECK (status IN ('ativo', 'suspenso_denuncia', 'removido')),
  revisao_solicitada boolean DEFAULT false NOT NULL,
  revisao_solicitada_em timestamp with time zone,
  comentario_admin text,
  busca tsvector GENERATED ALWAYS AS (
      setweight(to_tsvector('portuguese', COALESCE(titulo, '')), 'A')
      || setweight(to_tsvector('english', COALESCE(titulo, '')), 'A')
      || setweight(to_tsvector('portuguese', COALESCE(descricao, '')), 'B')
      || setweight(to_tsvector('english', COALESCE(descricao, '')), 'B')
  ) STORED,
  duracao_estimada_min integer CHECK (duracao_estimada_min > 0)
);

CREATE INDEX idx_conteudos_busca ON "CONTEUDOS" USING gin (busca);

CREATE TABLE "ARQUIVOS" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conteudo bigint NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  bucket_id text DEFAULT 'conteudos' NOT NULL,
  storage_path text NOT NULL,
  nome_original text,
  mime_type text,
  tamanho_bytes bigint,
  uploaded_by uuid
);

CREATE TABLE "DENUNCIAS" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conteudo bigint NOT NULL REFERENCES "CONTEUDOS"(id),
  id_aluno bigint NOT NULL REFERENCES "ALUNOS"(id),
  id_professor bigint NOT NULL REFERENCES "PROFESSORES"(id),
  motivo text NOT NULL,
  status text DEFAULT 'pendente' NOT NULL CHECK (status IN ('pendente', 'analisada_liberada', 'analisada_removida')),
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  UNIQUE (id_conteudo, id_aluno)
);

CREATE TABLE "DOMINIOS" (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  dominio text NOT NULL,
  status text DEFAULT 'pendente' NOT NULL CHECK (status IN ('pendente', 'aprovado', 'rejeitado')),
  id_professor bigint REFERENCES "PROFESSORES"(id),
  justificativa text,
  comentario_admin text,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  analisado_em timestamp with time zone
);

CREATE UNIQUE INDEX ux_dominios_ativos ON "DOMINIOS" (lower(dominio)) WHERE status IN ('pendente', 'aprovado');

CREATE TABLE "EVENTOS" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_turma bigint NOT NULL,
  id_professor bigint NOT NULL,
  titulo varchar(255) NOT NULL,
  tipo varchar(255) NOT NULL,
  descricao varchar(255) NOT NULL,
  data_hora timestamp without time zone NOT NULL,
  status varchar(255) NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  data_fim timestamp with time zone,
  prioridade varchar(255) DEFAULT 'MEDIA'
);

CREATE TABLE "EVENTO_CONTEUDO" (
  id_evecon bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evento bigint REFERENCES "EVENTOS"(id),
  id_conteudo bigint REFERENCES "CONTEUDOS"(id),
  UNIQUE (id_evento, id_conteudo)
);

CREATE TABLE "DISPONIBILIDADES" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aluno bigint NOT NULL REFERENCES "ALUNOS"(id) ON DELETE CASCADE,
  data date NOT NULL,
  horas_disponiveis integer NOT NULL CHECK (horas_disponiveis BETWEEN 0 AND 24),
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  UNIQUE (id_aluno, data)
);

CREATE TABLE "PROGRESSO_CONTEUDO" (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_aluno bigint NOT NULL REFERENCES "ALUNOS"(id),
  id_conteudo bigint NOT NULL REFERENCES "CONTEUDOS"(id),
  concluido_em timestamp with time zone DEFAULT now() NOT NULL,
  UNIQUE (id_aluno, id_conteudo)
);

CREATE TABLE "CHAMADOS" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario bigint NOT NULL REFERENCES "USUARIOS"(id) ON DELETE CASCADE,
  assunto varchar(150) NOT NULL,
  descricao text NOT NULL,
  status varchar(20) DEFAULT 'aberto' NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
  concluido_em timestamp with time zone,
  id_admin_conclusao bigint REFERENCES "USUARIOS"(id) ON DELETE SET NULL
);

CREATE TABLE "CHAMADO_RESPOSTAS" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_chamado bigint NOT NULL REFERENCES "CHAMADOS"(id) ON DELETE CASCADE,
  id_admin_usuario bigint REFERENCES "USUARIOS"(id) ON DELETE SET NULL,
  resposta text NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
  id_usuario bigint REFERENCES "USUARIOS"(id) ON DELETE SET NULL,
  tipo_autor varchar(10) DEFAULT 'admin' NOT NULL
);

CREATE TABLE "LOGS_SESSOES" (
  sessao_log_id uuid NOT NULL PRIMARY KEY,
  usuario_id bigint,
  inicio timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
  fim timestamp with time zone,
  status varchar(12) DEFAULT 'ATIVA' NOT NULL,
  log_completo text,
  historico_gerado_em timestamp with time zone
);

CREATE TABLE "LOGS_EVENTOS" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sessao_log_id uuid REFERENCES "LOGS_SESSOES"(sessao_log_id),
  data_hora timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
  nivel varchar(5) NOT NULL,
  classe varchar(255) NOT NULL,
  operacao varchar(100),
  operacao_id uuid,
  mensagem text NOT NULL,
  detalhes jsonb,
  excecao text
);
